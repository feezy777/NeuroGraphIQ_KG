@dataclass
class NodeInfo:
    """Lightweight node representation for graph algorithms."""
    region_id: str
    name_en: str = ""
    name_cn: str = ""
    functional_domains: list[str] = field(default_factory=list)


@dataclass
class EdgeRecord:
    """Lightweight edge record for graph algorithms."""
    edge_id: str
    source_id: str
    target_id: str
    connection_type: str = ""
    directionality: str = "directed"
    confidence: float = 0.0
    evidence_count: int = 0
    strength: str | None = None
    modality: str | None = None


@dataclass
class TopologyCandidate:
    """A single candidate topology generated by the graph engine."""

    topology_type: str
    anatomical_pattern: str
    is_closed: bool
    node_ids: list[str]
    edge_ids: list[str]
    canonical_key: str
    pre_score: float = 0.0
    avg_confidence: float = 0.0
    total_evidence: int = 0
    node_count: int = 0
    edge_count: int = 0
    extra: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        return {
            "topology_type": self.topology_type,
            "anatomical_pattern": self.anatomical_pattern,
            "is_closed": self.is_closed,
            "node_ids": self.node_ids,
            "edge_ids": self.edge_ids,
            "canonical_key": self.canonical_key,
            "pre_score": self.pre_score,
            "avg_confidence": self.avg_confidence,
            "total_evidence": self.total_evidence,
            "node_count": self.node_count,
            "edge_count": self.edge_count,
            **self.extra,
        }


