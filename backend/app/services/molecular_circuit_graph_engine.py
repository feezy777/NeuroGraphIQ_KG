# Graph Engine
# ---------------------------------------------------------------------------


class MolecularGraphEngine:
    """Generates candidate topologies from Mirror KG molecular connections.

    Design:
      - Builds in-memory adjacency from MirrorRegionConnection rows.
      - Computes SCC (Kosaraju), hubs (top 50 by degree).
      - Generates 9 motif types with per-type caps, real-time canonical dedup.
      - Pre-scores each candidate (0..1), filters below config.pre_score_cutoff.
      - Saves raw candidates to JSONL for downstream phases.
    """

    def __init__(self, config: GraphEngineConfig | None = None):
        self.config = config or GraphEngineConfig()

        # Graph data
        self.nodes: dict[str, NodeInfo] = {}
        self.adjacency: dict[str, set[str]] = {}
        self.reverse_adjacency: dict[str, set[str]] = {}
        self.edges: dict[str, EdgeRecord] = {}

        # Edge index: (source_id, target_id) -> list[edge_id]
        self._edge_by_pair: dict[tuple[str, str], list[str]] = {}

        # Region meta: region_id -> functional_domains
        self._functional_domains: dict[str, list[str]] = {}

        # SCC cache
        self.scc_components: list[set[str]] = []
        self.scc_index: dict[str, int] = {}

        # Hub cache
        self.hubs: list[str] = []
        self.hub_2hop: dict[str, set[str]] = {}

        # Global dedup set
        self._seen: set[str] = set()

        # Candidate accumulator
        self._candidates: list[TopologyCandidate] = []

        # Stats
        self._stats: dict[str, Any] = {
            "motif_counts": {},
            "motif_deduped": {},
            "motif_filtered": {},
            "total_generated": 0,
            "total_after_dedup": 0,
            "total_after_scoring": 0,
            "graph_build_ms": 0,
            "generation_ms": 0,
        }

    # ------------------------------------------------------------------
    # Data Loading
    # ------------------------------------------------------------------

    async def load_from_db(self, session: AsyncSession) -> None:
        """Load molecular connections from Mirror KG."""
        t0 = time.perf_counter()

        # 1. Load candidate brain regions for functional_domains
        region_stmt = select(CandidateBrainRegion).where(
            CandidateBrainRegion.granularity_level == self.config.granularity_level
        )
        region_result = await session.execute(region_stmt)
        region_rows: list[CandidateBrainRegion] = list(region_result.scalars())
        for row in region_rows:
            region_id = str(row.id)
            func_domains = row.raw_payload.get("functional_domains", []) if row.raw_payload else []
            if isinstance(func_domains, str):
                func_domains = [func_domains]
            self._functional_domains[region_id] = func_domains

        # 2. Load connections
        stmt = select(MirrorRegionConnection).where(
            MirrorRegionConnection.granularity_level == self.config.granularity_level
        )

        if self.config.exclude_rejected:
            from app.schemas.mirror_kg import MirrorReviewStatus
            stmt = stmt.where(MirrorRegionConnection.review_status != MirrorReviewStatus.rejected)

        if self.config.min_confidence is not None:
            stmt = stmt.where(
                MirrorRegionConnection.confidence >= self.config.min_confidence
            )

        result = await session.execute(stmt)
        conn_count = 0
        for row in result.scalars():
            conn_id = str(row.id)
            src_id = str(row.source_region_candidate_id) if row.source_region_candidate_id else ""
            tgt_id = str(row.target_region_candidate_id) if row.target_region_candidate_id else ""
            if not src_id or not tgt_id:
                continue

            # Upsert node info from candidate regions
            if src_id not in self.nodes:
                self.nodes[src_id] = NodeInfo(
                    region_id=src_id,
                    functional_domains=self._functional_domains.get(src_id, []),
                )
            if tgt_id not in self.nodes:
                self.nodes[tgt_id] = NodeInfo(
                    region_id=tgt_id,
                    functional_domains=self._functional_domains.get(tgt_id, []),
                )

            # Build adjacency
            if src_id not in self.adjacency:
                self.adjacency[src_id] = set()
            self.adjacency[src_id].add(tgt_id)

            if tgt_id not in self.reverse_adjacency:
                self.reverse_adjacency[tgt_id] = set()
            self.reverse_adjacency[tgt_id].add(src_id)

            # Build edge record
            evidence_count = 0
            raw_payload = row.raw_payload_json or {}
            if isinstance(raw_payload, dict):
                evidence_count = raw_payload.get("evidence_count", 0)
                if isinstance(evidence_count, str):
                    try:
                        evidence_count = int(evidence_count)
                    except (ValueError, TypeError):
                        evidence_count = 0
                elif not isinstance(evidence_count, (int, float)):
                    evidence_count = 0
                evidence_count = int(evidence_count) if evidence_count else 0

            self.edges[conn_id] = EdgeRecord(
                edge_id=conn_id,
                source_id=src_id,
                target_id=tgt_id,
                connection_type=row.connection_type or "",
                directionality=row.directionality or "directed",
                confidence=float(row.confidence) if row.confidence is not None else 0.0,
                evidence_count=evidence_count,
                strength=row.strength,
                modality=row.modality,
            )

            pair_key = (src_id, tgt_id)
            if pair_key not in self._edge_by_pair:
                self._edge_by_pair[pair_key] = []
            self._edge_by_pair[pair_key].append(conn_id)

            conn_count += 1

        elapsed = time.perf_counter() - t0
        self._stats["graph_build_ms"] = round(elapsed * 1000, 1)
        self._stats["node_count"] = len(self.nodes)
        self._stats["edge_count"] = len(self.edges)
        self._stats["connection_rows_loaded"] = conn_count
        logger.info(
            "Graph built: %d nodes, %d edges (from %d conn rows) in %.1fms",
            len(self.nodes), len(self.edges), conn_count, elapsed * 1000,
        )

        # 3. Populate name info from candidate region rows
        node_ids_with_names: set[str] = set()
        for row in region_rows:
            rid = str(row.id)
            if rid in self.nodes:
                self.nodes[rid].name_en = row.en_name or ""
                self.nodes[rid].name_cn = row.cn_name or ""
                node_ids_with_names.add(rid)

    # ------------------------------------------------------------------
    # SCC (Kosaraju)
    # ------------------------------------------------------------------

    def _kosaraju_scc(self) -> tuple[list[set[str]], dict[str, int]]:
        """Compute strongly connected components using Kosaraju's algorithm.

        Uses iterative DFS (avoiding Python recursion depth limits on
        574-node dense graphs) with explicit state stack.
        """
        all_nodes = list(self.nodes.keys())
        visited: set[str] = set()
        order: list[str] = []

        # First pass: DFS post-order (iterative).
        # State stack holds (node, iterator-over-neighbors) pairs.
        for start_node in all_nodes:
            if start_node in visited:
                continue
            call_stack: list[tuple[str, object]] = [(start_node, None)]
            while call_stack:
                v, it = call_stack[-1]
                if v not in visited:
                    visited.add(v)
                    it = iter(self.adjacency.get(v, set()))
                    call_stack[-1] = (v, it)
                # Advance iterator
                try:
                    nb = next(it)  # type: ignore[arg-type]
                    if nb not in visited:
                        call_stack.append((nb, None))
                except StopIteration:
                    call_stack.pop()
                    order.append(v)

        # Second pass: DFS on reversed graph in reverse finishing order.
        visited2: set[str] = set()
        components: list[set[str]] = []
        index: dict[str, int] = {}

        comp_id = 0
        for v in reversed(order):
            if v in visited2:
                continue
            comp: set[str] = set()
            stack = [v]
            while stack:
                cur = stack.pop()
                if cur not in visited2:
                    visited2.add(cur)
                    index[cur] = comp_id
                    comp.add(cur)
                    for nb in self.reverse_adjacency.get(cur, set()):
                        if nb not in visited2:
                            stack.append(nb)
            components.append(comp)
            comp_id += 1

        return components, index

    def compute_scc(self) -> None:
        """Compute and cache SCC components."""
        t0 = time.perf_counter()
        self.scc_components, self.scc_index = self._kosaraju_scc()
        elapsed = time.perf_counter() - t0
        self._stats["scc_count"] = len(self.scc_components)
        self._stats["scc_compute_ms"] = round(elapsed * 1000, 1)
        largest_scc = max((len(c) for c in self.scc_components), default=0)
        self._stats["largest_scc_size"] = largest_scc
        logger.info(
            "SCC: %d components, largest=%d nodes (%.1fms)",
            len(self.scc_components), largest_scc, elapsed * 1000,
        )

    # ------------------------------------------------------------------
    # Hubs
    # ------------------------------------------------------------------

    def compute_hubs(self) -> None:
        """Compute top-K hubs by total degree and their 2-hop neighborhoods."""
        t0 = time.perf_counter()

        degree: dict[str, int] = {}
        all_nodes = list(self.nodes.keys())
        for n in all_nodes:
            out_deg = len(self.adjacency.get(n, set()))
            in_deg = len(self.reverse_adjacency.get(n, set()))
            degree[n] = out_deg + in_deg

        sorted_nodes = sorted(degree.items(), key=lambda x: -x[1])
        self.hubs = [n for n, _ in sorted_nodes[:self.config.hub_count]]

        # Build 2-hop neighborhoods for hubs
        self.hub_2hop = {}
        for hub in self.hubs:
            neighbors: set[str] = set()
            # 1-hop forward
            for nb in self.adjacency.get(hub, set()):
                neighbors.add(nb)
                # 2-hop forward
                for nb2 in self.adjacency.get(nb, set()):
                    neighbors.add(nb2)
            # 1-hop backward
            for nb in self.reverse_adjacency.get(hub, set()):
                neighbors.add(nb)
                # 2-hop backward
                for nb2 in self.reverse_adjacency.get(nb, set()):
                    neighbors.add(nb2)
            neighbors.discard(hub)
            self.hub_2hop[hub] = neighbors

        elapsed = time.perf_counter() - t0
        self._stats["hub_compute_ms"] = round(elapsed * 1000, 1)
        logger.info(
            "Hubs: top-%d nodes by degree (%.1fms)",
            len(self.hubs), elapsed * 1000,
        )

    # ------------------------------------------------------------------
    # Helper: edge selection
    # ------------------------------------------------------------------

    def _get_edge_id(self, src: str, tgt: str) -> str | None:
        """Get the first edge_id for a given (source, target) pair."""
        ids = self._edge_by_pair.get((src, tgt))
        if ids:
            return ids[0]
        return None

    def _get_edge_ids(self, src: str, tgt: str) -> list[str]:
        """Get all edge_ids for a given (source, target) pair."""
        return self._edge_by_pair.get((src, tgt), [])

    def _avg_edge_confidence_for_ids(self, edge_ids: list[str]) -> float:
        """Average confidence across a list of edge IDs."""
        if not edge_ids:
            return 0.0
        total = 0.0
        count = 0
        for eid in edge_ids:
            rec = self.edges.get(eid)
            if rec is not None:
                total += rec.confidence
                count += 1
        return total / count if count > 0 else 0.0

    def _total_evidence_for_ids(self, edge_ids: list[str]) -> int:
        """Sum evidence_count across edge IDs."""
        total = 0
        for eid in edge_ids:
            rec = self.edges.get(eid)
            if rec is not None:
                total += rec.evidence_count
        return total

    def _check_and_dedup(self, canonical_key: str) -> bool:
        """Return True if this key is new (not yet seen)."""
        if canonical_key in self._seen:
            return False
        self._seen.add(canonical_key)
        return True

    # ------------------------------------------------------------------
    # Topology Pre-Scoring
    # ------------------------------------------------------------------

    def _anatomical_consistency(self, candidate: TopologyCandidate) -> float:
        """Score 0..1 for anatomical plausibility.

        Heuristic: prefer paths within same hemisphere / nearby regions.
        For now, use a simple heuristic based on edges having valid connection types.
        """
        if not candidate.edge_ids:
            return 0.0
        valid_types = 0
        for eid in candidate.edge_ids:
            rec = self.edges.get(eid)
            if rec and rec.connection_type and rec.connection_type != "unknown":
                valid_types += 1
        return valid_types / len(candidate.edge_ids)

    def _module_coherence(self, candidate: TopologyCandidate) -> float:
        """Score 0..1 for functional module coherence.

        If all nodes share functional domains, score is higher.
        """
        if not candidate.node_ids:
            return 0.0
        domain_sets: list[set[str]] = []
        for nid in candidate.node_ids:
            node = self.nodes.get(nid)
            if node and node.functional_domains:
                domain_sets.append(set(node.functional_domains))
        if not domain_sets:
            return 0.5  # neutral when no domain info
        # Jaccard-like overlap score
        if len(domain_sets) == 1:
            return 0.7
        intersection = set.intersection(*domain_sets) if len(domain_sets) > 1 else set()
        union = set.union(*domain_sets)
        if not union:
            return 0.5
        return len(intersection) / len(union)

    def _redundancy_penalty(self, candidate: TopologyCandidate) -> float:
        """Penalty 0..1 for redundancy with existing candidates.

        Penalize if this candidate shares many edges with higher-scored ones.
        Simplified: penalize based on degree of hub overlap.
        """
        node_set = set(candidate.node_ids)
        hub_overlap = sum(1 for h in self.hubs if h in node_set)
        if len(candidate.node_ids) == 0:
            return 0.0
        ratio = hub_overlap / len(candidate.node_ids)
        # Moderate penalty: 0 at ratio 0, 1 at ratio 1
        return ratio * 0.5

    def topology_pre_score(self, candidate: TopologyCandidate) -> float:
        """Compute pre-score 0..1 for ranking before LLM judgement."""
        score = 0.0

        # 1. Topology completeness (0-0.25)
        score += 0.25 * (1.0 if candidate.is_closed else 0.7)

        # 2. Average edge confidence (0-0.25)
        avg_conf = self._avg_edge_confidence_for_ids(candidate.edge_ids)
        score += 0.25 * avg_conf

        # 3. Evidence quantity (0-0.20)
        total_ev = candidate.total_evidence
        score += 0.20 * min(1.0, total_ev / 10.0)

        # 4. Anatomical consistency (0-0.15)
        score += 0.15 * self._anatomical_consistency(candidate)

        # 5. Module coherence (0-0.10)
        score += 0.10 * self._module_coherence(candidate)

        # 6. Redundancy penalty (0-0.05)
        score -= 0.05 * self._redundancy_penalty(candidate)

        return max(0.0, min(1.0, score))

    # ------------------------------------------------------------------
    # Candidate creation helper
    # ------------------------------------------------------------------

    def _make_candidate(
        self,
        topology_type: str,
        anatomical_pattern: str,
        is_closed: bool,
        node_ids: list[str],
        edge_ids: list[str],
        extra: dict[str, Any] | None = None,
    ) -> TopologyCandidate | None:
        """Create a TopologyCandidate with pre-score, checking dedup.

        Returns None if already seen or below score cutoff.
        """
        canonical_key = make_canonical_key(node_ids, topology_type)
        if not self._check_and_dedup(canonical_key):
            return None

        avg_conf = self._avg_edge_confidence_for_ids(edge_ids)
        total_ev = self._total_evidence_for_ids(edge_ids)

        candidate = TopologyCandidate(
            topology_type=topology_type,
            anatomical_pattern=anatomical_pattern,
            is_closed=is_closed,
            node_ids=node_ids,
            edge_ids=edge_ids,
            canonical_key=canonical_key,
            avg_confidence=avg_conf,
            total_evidence=total_ev,
            node_count=len(node_ids),
            edge_count=len(edge_ids),
            extra=extra or {},
        )

        candidate.pre_score = self.topology_pre_score(candidate)

        if candidate.pre_score < self.config.pre_score_cutoff:
            return None

        return candidate

    def _accumulate(self, candidate: TopologyCandidate | None) -> bool:
        """Accumulate candidate if not None. Returns True if added."""
        if candidate is None:
            return False
        self._candidates.append(candidate)
        return True

    # ------------------------------------------------------------------
    # Motif Generation
    # ------------------------------------------------------------------

    def generate_directed_cycles_3(self) -> int:
        """Generate A→B→C→A closed 3-node cycles."""
        count = 0
        deduped = 0
        filtered = 0
        motif_type = "directed_cycle_3"
        cap = self.config.max_directed_cycles_3

        for a in self.nodes:
            if count >= cap:
                break
            for b in self.adjacency.get(a, set()):
                if count >= cap:
                    break
                if b == a:
                    continue
                for c in self.adjacency.get(b, set()):
                    if count >= cap:
                        break
                    if c == a or c == b:
                        continue
                    if a in self.adjacency.get(c, set()):
                        edge_ids = []
                        e1 = self._get_edge_id(a, b)
                        e2 = self._get_edge_id(b, c)
                        e3 = self._get_edge_id(c, a)
                        if e1 and e2 and e3:
                            edge_ids = [e1, e2, e3]
                        cand = self._make_candidate(
                            topology_type=motif_type,
                            anatomical_pattern="closed_circuit",
                            is_closed=True,
                            node_ids=[a, b, c],
                            edge_ids=edge_ids,
                        )
                        if cand is None:
                            deduped += 1
                            continue
                        if self._accumulate(cand):
                            count += 1
                        else:
                            filtered += 1

        self._stats["motif_counts"][motif_type] = count
        self._stats["motif_deduped"][motif_type] = deduped
        self._stats["motif_filtered"][motif_type] = filtered
        logger.info("  directed_cycle_3: %d generated, %d deduped", count, deduped)
        return count

    def generate_feedforward_loops_3(self) -> int:
        """Generate A→B, A→C, B→C pattern (no closure requirement)."""
        count = 0
        deduped = 0
        filtered = 0
        motif_type = "feedforward_loop_3"
        cap = self.config.max_feedforward_loops_3

        for a in self.nodes:
            if count >= cap:
                break
            out_a = self.adjacency.get(a, set())
            if len(out_a) < 2:
                continue
            out_list = list(out_a)
            for bi in range(len(out_list)):
                if count >= cap:
                    break
                b = out_list[bi]
                if b == a:
                    continue
                for ci in range(bi + 1, len(out_list)):
                    if count >= cap:
                        break
                    c = out_list[ci]
                    if c == a or c == b:
                        continue
                    if b in self.adjacency.get(c, set()):
                        # Feedforward: A→B, A→C, C→B (B receives from C)
                        edge_ids = []
                        e1 = self._get_edge_id(a, b)
                        e2 = self._get_edge_id(a, c)
                        e3 = self._get_edge_id(c, b)
                        if e1 and e2 and e3:
                            edge_ids = [e1, e2, e3]
                        cand = self._make_candidate(
                            topology_type=motif_type,
                            anatomical_pattern="feedforward_motif",
                            is_closed=False,
                            node_ids=[a, c, b],
                            edge_ids=edge_ids,
                        )
                        if cand is None:
                            deduped += 1
                            continue
                        if self._accumulate(cand):
                            count += 1
                    elif c in self.adjacency.get(b, set()):
                        # Feedforward: A→B, A→C, B→C
                        edge_ids = []
                        e1 = self._get_edge_id(a, b)
                        e2 = self._get_edge_id(a, c)
                        e3 = self._get_edge_id(b, c)
                        if e1 and e2 and e3:
                            edge_ids = [e1, e2, e3]
                        cand = self._make_candidate(
                            topology_type=motif_type,
                            anatomical_pattern="feedforward_motif",
                            is_closed=False,
                            node_ids=[a, b, c],
                            edge_ids=edge_ids,
                        )
                        if cand is None:
                            deduped += 1
                            continue
                        if self._accumulate(cand):
                            count += 1

        self._stats["motif_counts"][motif_type] = count
        self._stats["motif_deduped"][motif_type] = deduped
        self._stats["motif_filtered"][motif_type] = filtered
        logger.info("  feedforward_loop_3: %d generated, %d deduped", count, deduped)
        return count

    def generate_reciprocal_pairs_3(self) -> int:
        """Generate A↔B AND B↔C chains (3-node reciprocal chain).

        Finds nodes where bidirectional edges exist and chains them.
        """
        count = 0
        deduped = 0
        filtered = 0
        motif_type = "reciprocal_pair_3"
        cap = self.config.max_reciprocal_pairs_3

        # Build bidirectional adjacency
        bidirectional: dict[str, set[str]] = {}
        for node in self.nodes:
            out_set = self.adjacency.get(node, set())
            in_set = self.reverse_adjacency.get(node, set())
            mutual = out_set & in_set
            if mutual:
                bidirectional[node] = mutual

        for a in bidirectional:
            if count >= cap:
                break
            for b in bidirectional.get(a, set()):
                if count >= cap:
                    break
                if b <= a:  # avoid A→B / B→A duplicates
                    continue
                for c in bidirectional.get(b, set()):
                    if count >= cap:
                        break
                    if c == a:
                        continue
                    if c in bidirectional.get(a, set()):
                        continue  # A↔C makes a triangle, skip
                    # A↔B and B↔C
                    edge_ids = []
                    e_ab = self._get_edge_id(a, b)
                    e_ba = self._get_edge_id(b, a)
                    e_bc = self._get_edge_id(b, c)
                    e_cb = self._get_edge_id(c, b)
                    if e_ab and e_ba and e_bc and e_cb:
                        edge_ids = [e_ab, e_ba, e_bc, e_cb]
                    cand = self._make_candidate(
                        topology_type=motif_type,
                        anatomical_pattern="feedback_motif",
                        is_closed=False,
                        node_ids=[a, b, c],
                        edge_ids=edge_ids,
                    )
                    if cand is None:
                        deduped += 1
                        continue
                    if self._accumulate(cand):
                        count += 1

        self._stats["motif_counts"][motif_type] = count
        self._stats["motif_deduped"][motif_type] = deduped
        self._stats["motif_filtered"][motif_type] = filtered
        logger.info("  reciprocal_pair_3: %d generated, %d deduped", count, deduped)
        return count

    def generate_convergent_motifs(self) -> int:
        """Generate A→C, B→C convergent motifs.

        Only for top-50 hubs as C (target). Max 20 per hub.
        """
        count = 0
        deduped = 0
        filtered = 0
        motif_type = "convergent_motif"
        cap = self.config.max_convergent_motifs
        max_per = self.config.max_per_hub_convergent

        for hub in self.hubs:
            if count >= cap:
                break
            in_neighbors = list(self.reverse_adjacency.get(hub, set()))
            if len(in_neighbors) < 2:
                continue
            per_hub = 0
            for ai in range(len(in_neighbors)):
                if count >= cap or per_hub >= max_per:
                    break
                a = in_neighbors[ai]
                if a == hub:
                    continue
                for bi in range(ai + 1, len(in_neighbors)):
                    if count >= cap or per_hub >= max_per:
                        break
                    b = in_neighbors[bi]
                    if b == hub or b == a:
                        continue
                    edge_ids = []
                    e1 = self._get_edge_id(a, hub)
                    e2 = self._get_edge_id(b, hub)
                    if e1 and e2:
                        edge_ids = [e1, e2]
                    # Canonical key: sorted sources
                    sorted_sources = sorted([a, b])
                    ck = canonical_key_convergent(sorted_sources, hub)
                    if not self._check_and_dedup(ck):
                        deduped += 1
                        continue
                    avg_conf = self._avg_edge_confidence_for_ids(edge_ids)
                    total_ev = self._total_evidence_for_ids(edge_ids)
                    cand = TopologyCandidate(
                        topology_type=motif_type,
                        anatomical_pattern="convergent_motif",
                        is_closed=False,
                        node_ids=[a, b, hub],
                        edge_ids=edge_ids,
                        canonical_key=ck,
                        avg_confidence=avg_conf,
                        total_evidence=total_ev,
                        node_count=3,
                        edge_count=len(edge_ids),
                    )
                    cand.pre_score = self.topology_pre_score(cand)
                    if cand.pre_score < self.config.pre_score_cutoff:
                        filtered += 1
                        continue
                    if self._accumulate(cand):
                        count += 1
                        per_hub += 1

        self._stats["motif_counts"][motif_type] = count
        self._stats["motif_deduped"][motif_type] = deduped
        self._stats["motif_filtered"][motif_type] = filtered
        logger.info("  convergent_motif: %d generated, %d deduped", count, deduped)
        return count

