# ---------------------------------------------------------------------------
# Canonical key functions
# ---------------------------------------------------------------------------

MOTIF_CLOSED_TYPES = frozenset({
    "directed_cycle_3",
    "closed_loop_4_8",
    "cortico_subcortical_loop",
    "cross_module_loop",
})


def canonical_key_directed_cycle(node_ids: list[str]) -> str:
    """Rotate to lexicographically minimal start for directed cycles."""
    if not node_ids:
        return ""
    rotations = [node_ids[i:] + node_ids[:i] for i in range(len(node_ids))]
    return "::".join(min(rotations))


def canonical_key_pathway(node_ids: list[str]) -> str:
    """Keep direction, normalize so start < end lexicographically."""
    if not node_ids:
        return ""
    if node_ids[0] < node_ids[-1]:
        return "::".join(node_ids)
    return "::".join(reversed(node_ids))


def canonical_key_convergent(sources: list[str], target: str) -> str:
    """Sort sources alphabetically, then target."""
    sorted_sources = sorted(sources)
    return f"convergent::{':'.join(sorted_sources)}->{target}"


def canonical_key_divergent(source: str, targets: list[str]) -> str:
    """Source first, then sorted targets."""
    sorted_targets = sorted(targets)
    return f"divergent::{source}->{':'.join(sorted_targets)}"


def canonical_key_reciprocal(node_ids: list[str]) -> str:
    """Reciprocal pair chain: rotate to lexicographically minimal start."""
    if not node_ids:
        return ""
    rotations = [node_ids[i:] + node_ids[:i] for i in range(len(node_ids))]
    return "reciprocal::" + "::".join(min(rotations))


def make_canonical_key(node_ids: list[str], topology_type: str) -> str:
    """Dispatch to the correct canonical key function based on type."""
    if topology_type in MOTIF_CLOSED_TYPES:
        return canonical_key_directed_cycle(node_ids)
    elif topology_type == "reciprocal_pair_3":
        return canonical_key_reciprocal(node_ids)
    elif topology_type in ("convergent_motif",):
        # For convergent, we store [source, source, target] — handle specially
        if len(node_ids) >= 2:
            return canonical_key_convergent(node_ids[:-1], node_ids[-1])
        return "::".join(node_ids)
    elif topology_type in ("divergent_motif",):
        # For divergent, we store [source, target, target]
        if len(node_ids) >= 2:
            return canonical_key_divergent(node_ids[0], node_ids[1:])
        return "::".join(node_ids)
    else:
        return canonical_key_pathway(node_ids)


